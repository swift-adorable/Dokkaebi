/// <summary>
/// 풀에서 꺼내지고 되돌려질 때 상태를 초기화해야 하는 오브젝트가 구현한다.
///
/// 풀링의 가장 흔한 버그는 '이전 사용 때의 상태가 남아 있는 것'이다.
/// (예: 체력 0인 적이 그대로 재사용되어 즉사, 이미 소비된 총알이 피해를 주지 않음)
/// 이 인터페이스는 그 초기화 지점을 강제한다.
/// </summary>
public interface IPoolable
{
    /// <summary>풀에서 꺼내져 활성화된 직후 호출된다. 여기서 상태를 초기화한다.</summary>
    void OnSpawned();

    /// <summary>풀로 되돌아가기 직전에 호출된다. 여기서 참조를 해제한다.</summary>
    void OnDespawned();
}

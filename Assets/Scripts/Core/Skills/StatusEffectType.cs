/// <summary>
/// 적에게 걸리는 상태 — v5 §5-1.
///
/// 모든 Skill은 '생성하는 상태'와 '소비하는 상태'를 명시한다.
/// 조합 가능 여부는 이 매칭으로 자동 결정되며, 개별 조합 규칙을 코드에 쓰지 않는다.
/// (마스터 프롬프트 10-2 [2])
/// </summary>
public enum StatusEffectType
{
    None = 0,

    /// <summary>점화 — 화염이 부여. 초당 화염 피해. 소비 시 화염 폭발 + 화염 지대.</summary>
    Ignite = 1,

    /// <summary>중독 — 역병이 부여. 중첩형 지속 피해(최대 10). 소비 시 독 구름 확산.</summary>
    Poison = 2,

    /// <summary>동결 — 【위험 상태】 냉각이 최대 중첩에 도달하면 전이한다. 행동 불능.</summary>
    Freeze = 3,

    /// <summary>감전 — 뇌전이 부여. 받는 모든 피해 +20%. 소비 시 낙뢰 3회.</summary>
    Shock = 4,

    /// <summary>출혈 — 열상이 부여. 이동 중인 적에게 피해 배증. 소비 시 혈액 분출.</summary>
    Bleed = 5,

    /// <summary>응집 — 중력 붕괴가 부여. 상태 전이 범위 2배.</summary>
    Congeal = 6,

    /// <summary>냉각 — 서리가 부여. 이동·공격 속도 감소. 최대 중첩에서 동결로 전이한다.</summary>
    Chill = 7,

    // ── 위험 상태 ─────────────────────────────────────────────────────
    // 중첩이 차면 질적으로 다른 것이 된다. 직접 부여되지 않고 전이로만 생긴다.
    // 전이 시 원본 중첩을 전부 소모하므로 끝나면 처음부터 다시 쌓아야 한다 —
    // 무한 제압을 막는 장치다. (docs/Dokkaebi_Combat_Baseline.md 「상태이상」)

    /// <summary>마비 — 【위험 상태】 감전이 최대 중첩에 도달하면 전이한다. 행동 불능.</summary>
    Paralyze = 8,

    /// <summary>부식 — 【위험 상태】 중독이 최대 중첩에 도달하면 전이한다. 방어도·회복량 절반.</summary>
    Corrode = 9,

    // ── 이로운 상태 ───────────────────────────────────────────────────
    //
    // 【해로운 것과 같은 배열에 둔다.】 소모품 문서 8절이 「효과는
    // StatusEffectType + 지속시간으로 표현한다. 전용 효과 필드를 새로
    // 만들지 않는다」로 정해 둔 것을 따른다. 축을 따로 파면 지속시간·중첩·
    // 갱신 규칙을 두 벌 관리하게 되고, 화면도 두 곳을 읽어야 한다.
    //
    // 【대가도 같은 방식이다.】 축지환의 「끝나면 −15%」는 별도 필드가
    // 아니라 만료 시 부여되는 다른 상태(쇠약)다.

    /// <summary>가속 — 축지환이 부여. 이동 속도 증가. 끝나면 쇠약이 온다.</summary>
    Haste = 10,

    /// <summary>강화 — 녹용이 부여. 방어도 증가, 대신 회복량 절반.</summary>
    Bolster = 11,

    /// <summary>회복 — 경옥고가 부여. 초당 체력 회복.</summary>
    Regen = 12,

    /// <summary>쇠약 — 【대가.】 가속이 끝나면 저절로 걸린다. 이동 속도 감소.</summary>
    Fatigue = 13,

    /// <summary>적재 — 공진단이 부여. 최대 소지 중량 증가.</summary>
    Overload = 14,

    // ── 저항 주사약 — 속성 저항 ──────────────────────────────────────────────
    //
    // 덕코프의 저항 buff 넷(#1072 · #1074 · #1075 …)과 같다.
    // 「받는 해당 속성 피해 배율 −25%」 · 120초 · 비배타. [확인됨]
    // 비배타이므로 넷을 동시에 걸 수 있다 — 다만 넷을 다 쓰면 수분이 −80이다.

    /// <summary>화염 저항 — 받는 화염 피해 감소.</summary>
    WardFire = 15,

    /// <summary>냉기 저항 — 받는 냉기 피해 감소.</summary>
    WardCold = 16,

    /// <summary>전기 저항 — 받는 번개 피해 감소.</summary>
    WardLightning = 17,

    /// <summary>독 저항 — 받는 카오스 피해 감소.</summary>
    WardChaos = 18,

    /// <summary>
    /// 폭주 — 부자탕(보스 약품)이 부여. 방어도·이동·최대 체력이 오르는 대신
    /// 【1초마다 체력이 깎인다.】 덕코프 「타길라의 힘」#1206과 같다.
    ///
    /// 이름을 「흡수」로 두지 않는다 — 흡수는 플레이어의 기본 행동(흡수 범위)이다.
    /// </summary>
    Frenzy = 19,

    // ── 막이 넷 — 궂은 날 (결정 2-63 · 2-91) ───────────────────────────────
    // 막이 소모품이 건다. 걸려 있는 동안 그 막이 +1 · 120초. 비배타 (넷을 같이 걸 수 있다).

    /// <summary>방한 — 겨울 한파.</summary>
    GuardWarmth = 20,

    /// <summary>막이 — 봄 흙비.</summary>
    GuardShield = 21,

    /// <summary>서늘함 — 여름 폭염 · 독안개.</summary>
    GuardCool = 22,

    /// <summary>밝히기 — 가을 짙은 안개.</summary>
    GuardLight = 23
}

/// <summary>바닥에 남는 지형 상태 — v5 §5-2.</summary>
public enum GroundEffectType
{
    None = 0,

    /// <summary>화염 지대 — 점화된 적 사망 시 생성. 진입 시 점화.</summary>
    FireZone = 1,

    /// <summary>독성 늪 — 중독된 적 사망 시 생성. 이동속도 감소 + 중독 중첩.</summary>
    ToxicSwamp = 2,

    /// <summary>서리 장판 — 동결된 적 사망 시 생성. 이동속도 감소, 냉기 누적 가속.</summary>
    FrostField = 3,

    /// <summary>혈액 지대 — 출혈 적 사망 시 생성. 진입 시 출혈.</summary>
    BloodZone = 4,

    /// <summary>중력 우물 — 중력 붕괴가 생성. 흡입 + 응집 부여.</summary>
    GravityWell = 5,

    /// <summary>
    /// 【속성은 꽂힌 핵심 젬이 정한다.】 보조 젬이 쓰는 값이다.
    ///
    /// 「마름쇠」는 잔류물을 남기는 보조 젬인데 FireZone으로 고정돼 있었다.
    /// 서리 핵심 젬에 꽂아도 불바다가 생긴다는 뜻이고, 이는
    /// 「무기 = 기본값 / 핵심 젬 = 속성 / 보조 젬 = 궤도」라는 전투 3층
    /// 원칙을 보조 젬이 깨는 것이다. (Master_Prompt 기획 확정 현황)
    ///
    /// 실제 종류는 GroundEffectTable.Resolve가 핵심 젬의 부여 상태로 정한다.
    /// </summary>
    FromCoreAilment = 6
}

/// <summary>
/// 레이드 특성 10종 — 【맵 전체】에 걸리는 조건.
/// (docs/Blob_Hunting_System.md 9절)
///
/// 【장 수를 늘리지 않고 조우를 다양하게 만드는 축이다.】
/// 맵을 하나 더 만드는 것이 가장 비싼데, 같은 맵에 특성만 갈아 끼우면
/// "이번 판은 물리가 안 먹힌다"가 되어 빌드를 바꿔야 한다.
///
/// ⚠️ 저항은 【곱해지지 않는다】. 가장 낮은 배율 하나만 남는다.
///    「돌을 삼킨 잡귀」 레이드(물리 ×0.5) + 「경화」 적(물리 ×0.5) → ×0.5다. ×0.25가 아니다.
///    곱연산이면 원천 두 개만으로 "이 속성으로는 못 잡는다"가 되고,
///    상태이상 피해에도 상성이 곱해지므로 방어도 무시라는 우회로까지 막힌다.
///    철수 루팅에서 그건 파밍을 버리라는 뜻이다. (문서 9절)
/// </summary>
public enum RaidTrait
{
    None = 0,

    // ── 배치 계열 ─────────────────────────────────────────────────────
    // 둘은 정반대라 같이 걸리지 않는다. (문서 9절 ※)

    /// <summary>떼 지은 밤 — 무리가 크고 좁게 뭉친다. 전령이 최대 가치를 낸다.</summary>
    Dense = 1,

    /// <summary>흩어진 밤 — 무리가 작고 넓게 흩어진다. 하나씩 끊어 잡게 된다.</summary>
    Scattered = 2,

    // ── 저항 계열 ─────────────────────────────────────────────────────
    // 속성 5종에 하나씩 대응한다. 「남은 속성을 쓰면 된다」를 즉시 판단할 수 있어야
    // 하므로, 한 판에 저항 특성을 둘 이상 걸지 않는다. (RaidConditions)

    /// <summary>돌을 삼킨 잡귀 — 물리 ×0.5. 답은 속성 전환.</summary>
    Hardened = 3,

    /// <summary>불을 삼킨 잡귀 — 화염 ×0.5.</summary>
    FireProof = 4,

    /// <summary>얼음을 삼킨 잡귀 — 냉기 ×0.5.</summary>
    ColdAdapted = 5,

    /// <summary>벼락을 삼킨 잡귀 — 번개 ×0.5.</summary>
    Insulated = 6,

    /// <summary>독을 삼킨 잡귀 — 카오스 ×0.5.</summary>
    Antibody = 7,

    // ── 그 외 ─────────────────────────────────────────────────────────

    /// <summary>되살아나는 잡귀 — 적이 초당 회복한다. 화력이 모자라면 못 죽인다.</summary>
    Regenerating = 8,

    /// <summary>
    /// 피 없는 잡귀 — 출혈이 걸리지 않는다.
    ///
    /// 【불확실 — 문서에 효과가 없다.】 이름만 적혀 있다.
    /// 「피가 굳는다」를 그대로 읽어 출혈을 막는 것으로 뒀다.
    /// 저항 배율을 또 만들지 않은 이유 — 저항 특성이 이미 다섯이라
    /// 여섯 번째를 만들면 「남은 속성」이 줄어든다. 상태이상 축을 건드린다.
    /// </summary>
    Congealed = 9,

    /// <summary>
    /// 눅눅한 밤 — 장비 내구도가 빨리 닳는다.
    ///
    /// 【불확실 — 문서에 효과가 없다.】
    /// 「대기가 부식성」을 그대로 읽었다. 전투를 어렵게 하는 대신
    /// 「오래 있을수록 손해」를 만든다 — 철수 루팅에서 가장 값싼 압박이다.
    /// </summary>
    Corrosive = 10
}

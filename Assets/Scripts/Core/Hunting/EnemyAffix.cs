/// <summary>
/// 몬스터 속성 13종. (docs/Dokkaebi_Hunting_System.md 3절)
///
/// 【개체 단위 수식어다.】 맵 단위인 레이드 특성 10종과 혼동하지 않는다.
///
/// 【「갑각」과 「경화」는 다른 축이다 — 두 시스템의 분업 지점이다.】
///   갑각(방어도)은 【장비】의 방어 관통으로 뚫고,
///   경화(저항)는 【젬】의 속성 전환으로 우회한다.
/// 상태이상은 방어도를 무시하므로 갑각에는 도트가 답이지만 경화에는 통하지 않는다.
/// </summary>
public enum EnemyAffix
{
    None = 0,

    // ── 방어 5 ────────────────────────────────────────────────────────
    /// <summary>갑각 — 방어도 +3. 답은 방어 관통 또는 상태이상.</summary>
    Carapace = 1,

    /// <summary>경화 — 물리 저항 ×0.5. 답은 속성 전환.</summary>
    Hardened = 2,

    /// <summary>내화성 — 화염 저항 ×0.5.</summary>
    FireProof = 3,

    /// <summary>절연성 — 번개 저항 ×0.5.</summary>
    Insulated = 4,

    /// <summary>독 견딤 — 카오스 저항 ×0.5.</summary>
    Antibody = 5,

    /// <summary>
    /// 내한성 — 냉기 저항 ×0.5.
    ///
    /// 【문서 3절에 없던 것을 더했다 — 근거를 남긴다.】
    /// Dokkaebi의 피해 속성은 물리·화염·냉기·번개·카오스 5종인데,
    /// 방어 속성은 그중 넷(경화·내화성·절연성·독 견딤)만 막고 있었다.
    /// 냉기만 개별 저항하는 적이 없다는 뜻이고, 그러면 냉기 빌드만
    /// 「저항을 만나 답을 바꾸는」 경험을 하지 않는다.
    /// 의도된 비대칭이라는 서술은 문서 어디에도 없다.
    ///
    /// 레이드 특성 10종에는 「얼음을 삼킨 잡귀」이 이미 있어, 냉기가 저항 축에서
    /// 빠진 것이 설계가 아니라 누락임을 뒷받침한다. (문서 9절)
    /// PoE2에도 Cold Resistant가 있다.
    /// [확인됨 — docs/research/poe2/01_몬스터_속성.md]
    ///
    /// ⚠️ 이것으로 속성이 13종 → 14종이 된다. 되돌리려면 이 항목과
    /// EnemyAffixTable의 세 군데(Every · GroupOf · TryGetResistance)를 지운다.
    /// </summary>
    Cryostable = 14,

    // ── 생존 3 ────────────────────────────────────────────────────────
    /// <summary>재생 — 초당 회복. 답은 즉발 화력.</summary>
    Regenerating = 6,

    /// <summary>껍질 — 첫 피격 1회 무효. 답은 다중 적중.</summary>
    Shell = 7,

    /// <summary>분열성 — 사망 시 2마리로 분열. 답은 광역.</summary>
    Splitting = 8,

    // ── 공격 3 ────────────────────────────────────────────────────────
    /// <summary>신속 — 이동 +40%. 답은 동결 / 밀어내기.</summary>
    Swift = 9,

    /// <summary>
    /// 과민 — 예비동작 0.35 → 0.2초.
    ///
    /// ⚠️ 【시각 신호가 구현되기 전까지 붙이지 않는다.】
    /// 보이지 않는 단축은 난이도가 아니라 불공정이다. (문서 3절 경고)
    /// EnemyAffixTable.IsEnabled가 false를 돌려준다.
    /// </summary>
    Hair = 10,

    /// <summary>육중 — 밀어내기·기절 면역, 이동 −20%. 답은 거리 유지.</summary>
    Hulking = 11,

    // ── 지원 2 ────────────────────────────────────────────────────────
    /// <summary>전파 — 주변 일반 적 강화. 먼저 처치해야 한다.</summary>
    Broadcast = 12,

    /// <summary>잔향 — 사망 시 속성 1개를 주변에 넘긴다. 처치 순서가 중요해진다.</summary>
    Echo = 13
}

/// <summary>속성 분류. 조합 금지 규칙이 이 분류를 본다.</summary>
public enum EnemyAffixGroup
{
    Defence = 0,
    Survival = 1,
    Offence = 2,
    Support = 3
}
